import { listScripts, createScript } from './scripts.js';

const SEED_KEY = 'speech.demoSeeded';

const DEMO_TITLE = 'Попробуйте меня';

const DEMO_BODY = `Привет!

Это демо-скрипт. Можно удалить — он своё отслужил.

Тапните круглую кнопку снизу — и текст поедет сам. По бокам экрана две зоны: слева медленнее, справа быстрее. Шестерёнка слева сверху открывает настройки: размер шрифта, ширина, положение линии чтения, зеркало.

Если разрешите микрофон, текст будет следовать за вашим голосом. Просто читайте вслух — слова подсветятся по очереди, прямо как у настоящего ведущего.

Голосовые команды (просто скажите слово дважды):
«стоп стоп» — пауза.
«старт старт» — продолжаем.
«сначала сначала» — к началу.

Если что-то идёт не так и команда не срабатывает, попробуйте wake-слово: «суфлёр стоп», «суфлёр старт», «суфлёр сначала». Можно говорить «speech» вместо «суфлёр».

Скорость с микрофоном подстраивается под вас сама. А без микрофона её можно регулировать пальцами: тап слева — медленнее, справа — быстрее.

Поставьте телефон в стекло суфлёра перед камерой и читайте отражение — для этого в настройках включено «зеркало по горизонтали».

Готовы? Закройте этот текст крестиком слева и создайте свой первый скрипт через плюс в правом верхнем углу. Удачи в эфире.`;

export async function seedDemoScriptIfFirstRun() {
  try {
    if (localStorage.getItem(SEED_KEY) !== null) return null;
    const existing = await listScripts();
    if (existing.length > 0) {
      // Уже есть скрипты — это не первый запуск (например, миграция
      // старого пользователя). Помечаем seeded и не создаём демо.
      localStorage.setItem(SEED_KEY, '1');
      return null;
    }
    const created = await createScript({
      title: DEMO_TITLE,
      body: DEMO_BODY,
    });
    localStorage.setItem(SEED_KEY, '1');
    return created;
  } catch {
    /* localStorage может быть недоступен (private mode) — silently skip */
    return null;
  }
}
