import { listScripts, createScript } from './scripts.js';

const SEED_KEY = 'speech.demoSeeded';

const DEMO_TITLE = 'Попробуйте меня';

const DEMO_BODY = `Окей. Расскажу про этот телесуфлёр.

Я сделал его сам, потому что устал бороться с чужими: то скорость надо подкручивать каждые тридцать секунд, то текст уезжает не туда, то подписка на пятьсот рублей в месяц за функции, которыми не пользуешься.

Этот суфлёр читает вас. Не наоборот. Включаете микрофон — он слушает голос и сам подстраивается под ваш темп. Замедлились на сложном слове? Текст замедлится. Ускорились в эмоциональном куске? Догонит. Без пультов, без педалей, без молитв.

Если в эфире что-то пошло не так — скажите «стоп стоп», и текст замрёт. «Старт старт» — продолжит. «Сначала сначала» — вернёт к началу. Слово дважды подряд — это сигнал «обратись ко мне», в обычной речи такое почти не встречается.

Без микрофона тоже всё работает. Жмёте Play — текст едет сам. По бокам экрана две зоны: тапаете слева — текст съезжает влево, справа — вправо. Удобно подогнать под лицо в кадре. Сверху по центру две стрелки — двигают текст вверх и вниз тонким шагом для точной подгонки.

Шестерёнка слева сверху — настройки на ходу: шрифт, ширина, линия чтения, зеркало, скорость. Включите зеркало по горизонтали, поставьте телефон в стекло суфлёра перед камерой — и читайте отражение, как настоящий ведущий.

Этот скрипт — демо. Удалите его, когда наиграетесь, и создайте свой через плюс в правом углу. И главное: расслабьтесь. Текст здесь ведёте вы, а не он вас.`;

export async function seedDemoScriptIfFirstRun() {
  try {
    if (localStorage.getItem(SEED_KEY) !== null) return null;
    const existing = await listScripts();
    if (existing.length > 0) {
      // Уже есть скрипты — это не первый запуск (например, миграция
      // старого пользователя). Помечаем seeded и не создаём демо.
      localStorage.setItem(SEED_KEY, '1');
      return null;
    }
    const created = await createScript({
      title: DEMO_TITLE,
      body: DEMO_BODY,
    });
    localStorage.setItem(SEED_KEY, '1');
    return created;
  } catch {
    /* localStorage может быть недоступен (private mode) — silently skip */
    return null;
  }
}
