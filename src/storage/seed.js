import { listScripts, createScript } from './scripts.js';

const SEED_KEY = 'speech.demoSeeded';

const DEMO_TITLE = 'Почему это самый крутой телесуфлёр';

const DEMO_BODY = `Сейчас расскажу.

Главная фишка — этот суфлёр подстраивается под вас, а не наоборот. В обычных суфлёрах вы постоянно сидите с пультом или педалью и регулируете скорость, чтобы не отстать и не уехать вперёд. Запнулись на сложном слове — суфлёр уже улетел, паника. Ускорились в эмоциональном куске — суфлёр плетётся сзади, и в кадре видно, что вы читаете.

Здесь по-другому. Включаете микрофон, читаете как обычно — и текст сам идёт за вашим голосом. Подсветка ползёт по словам ровно с той скоростью, с которой вы их произносите. Запнулись — суфлёр ждёт. Заторопились — догоняет. Никакой гонки.

И ещё одно. Этот суфлёр полностью бесплатный. Никаких подписок, разовых покупок, скрытых платежей. Я не возьму с вас денег ни сейчас, ни через год, ни через пять лет. И сюда никогда не попадёт реклама. Серьёзно — никогда. Я делал его для себя, а раз сделал — пусть пользуются и другие.

Это всё. Открывайте плюс в правом верхнем углу, создавайте свой первый скрипт и забывайте про педали.`;

export async function seedDemoScriptIfFirstRun() {
  try {
    if (localStorage.getItem(SEED_KEY) !== null) return null;
    const existing = await listScripts();
    if (existing.length > 0) {
      // Уже есть скрипты — это не первый запуск (например, миграция
      // старого пользователя). Помечаем seeded и не создаём демо.
      localStorage.setItem(SEED_KEY, '1');
      return null;
    }
    const created = await createScript({
      title: DEMO_TITLE,
      body: DEMO_BODY,
    });
    localStorage.setItem(SEED_KEY, '1');
    return created;
  } catch {
    /* localStorage может быть недоступен (private mode) — silently skip */
    return null;
  }
}
